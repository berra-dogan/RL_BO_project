"""Summarize output/earlbo_grid results into a lookup dict.

Reads every RL_BO_*.csv under output/earlbo_grid/dimension_*/horizon_*/<function>/
and writes a (function, dimension, horizon) -> mean per-step Avg Scaled Move Cost
dict to src/experiments/earlbo_avg_scaled_move_cost.py.

The output lives under src/ (not output/) because budgeted_exploration and
lookahead_budgeted_exploration import it to compute a calibrated movement
budget during tuning/testing, so it needs to reach the cluster via the normal
sync_to_cluster.sh code sync, not the gitignored/unsynced output/ tree.
"""

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GRID_ROOT = ROOT / "output" / "earlbo_grid"
OUTPUT_PATH = ROOT / "src" / "experiments" / "earlbo_avg_scaled_move_cost.py"


def mean_avg_scaled_move_cost(csv_path):
    with csv_path.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        return None
    values = [float(row["Avg Scaled Move Cost"]) for row in rows]
    return sum(values) / len(values)


def collect():
    results = {}
    for csv_path in sorted(GRID_ROOT.glob("dimension_*/horizon_*/*/RL_BO_*.csv")):
        function_name = csv_path.parent.name
        horizon = int(csv_path.parent.parent.name.removeprefix("horizon_"))
        dimension = int(csv_path.parent.parent.parent.name.removeprefix("dimension_"))
        value = mean_avg_scaled_move_cost(csv_path)
        if value is not None:
            results[(function_name, dimension, horizon)] = value
    return results


def write_dict(results, output_path):
    lines = [
        "# Generated by src/experiments/summarize_earlbo_grid.py",
        "# Key: (function, dimension, horizon) -> mean per-step Avg Scaled Move Cost",
        "EARLBO_AVG_SCALED_MOVE_COST = {",
    ]
    for (function_name, dimension, horizon), value in sorted(results.items()):
        lines.append(f'    ("{function_name}", {dimension}, {horizon}): {value!r},')
    lines.append("}")
    output_path.write_text("\n".join(lines) + "\n")


def main():
    results = collect()
    write_dict(results, OUTPUT_PATH)
    print(f"Wrote {len(results)} entries to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
